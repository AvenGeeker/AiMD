import { Menu, Tray, app, nativeImage } from 'electron';
import { getHotkeyState } from './hotkey.js';
import { createMainWindow, showMainWindow, toggleCaptureWindow, getCaptureWindow } from './windows.js';
import { getState, isPlaintextFallback } from './store.js';
import { setQuitting } from './lifecycle.js';
import type { AppleNotesStatus } from '@aimarkdown/shared';

/**
 * Menu-bar / notification-area tray.
 *
 * The tray is what keeps the app reachable after the main window is closed, which matters because
 * the whole point of the desktop shell is the global quick-capture hotkey.
 */

// Embedded rather than read from disk so it resolves identically in dev and inside a packaged
// asar. Generated by scripts/make-icons.py (macOS template image: alpha only, adapts to the bar).
const TRAY_DATA_URL = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAABYAAAAWCAYAAADEtGw7AAAALklEQVR42mNgGAWDAfzHg6luINkW/CcDD5zB/0cNHjWYfgYzDEmDaVZWjALqAQBX5rJOKlUdIwAAAABJRU5ErkJggg==';

let tray: Tray | null = null;
let syncLabel = '同步状态未知';
let onQuit: (() => void) | null = null;
let appleNotesStatus: AppleNotesStatus | null = null;
let onAppleNotesSync: (() => void) | null = null;

export function setSyncLabel(label: string): void {
  syncLabel = label;
  rebuildMenu();
}

export function setQuitHandler(handler: () => void): void {
  onQuit = handler;
}

export function setAppleNotesStatus(status: AppleNotesStatus, onSync: () => void): void {
  appleNotesStatus = status;
  onAppleNotesSync = onSync;
  rebuildMenu();
}

function appleNotesLabel(status: AppleNotesStatus): string {
  if (!status.settings.enabled) return '备忘录：未启用';
  if (status.phase === 'error') return `备忘录：同步失败`;
  if (status.phase === 'needs-attention') return `备忘录：需要处理`;
  if (status.running) return '备忘录：同步中…';
  if (!status.settings.firstSyncConfirmedAt) return '备忘录：等待首次预览';
  return status.lastSyncAt ? `备忘录：已同步 ${new Date(status.lastSyncAt).toLocaleTimeString('zh-CN', { hour: '2-digit', minute: '2-digit' })}` : '备忘录：待同步';
}

function trayImage(): Electron.NativeImage {
  const image = nativeImage.createFromDataURL(TRAY_DATA_URL);
  // On macOS a template image is recoloured by the system for light/dark menu bars.
  if (process.platform === 'darwin') image.setTemplateImage(true);
  return image;
}

function rebuildMenu(): void {
  if (!tray) return;
  const hotkey = getHotkeyState();
  const state = getState();

  const hotkeyLabel = hotkey.registered
    ? `速记快捷键：${hotkey.accelerator}`
    : `快捷键未注册：${hotkey.accelerator || '（未设置）'}`;

  const menu = Menu.buildFromTemplate([
    {
      label: '唤起速记窗口',
      click: () => toggleCaptureWindow(),
    },
    {
      label: '打开主窗口',
      click: () => showMainWindow(),
    },
    { type: 'separator' },
    { label: syncLabel, enabled: false },
    {
      label: hotkeyLabel,
      enabled: false,
    },
    ...(hotkey.registered
      ? []
      : [
          {
            label: hotkey.error ? `⚠ ${hotkey.error}` : '⚠ 快捷键注册失败，请在设置中更换',
            enabled: false,
          },
        ]),
    ...(appleNotesStatus
      ? [
          { type: 'separator' as const },
          { label: appleNotesLabel(appleNotesStatus), enabled: false },
          ...(appleNotesStatus.settings.enabled
            ? [{ label: '立即同步备忘录', click: () => onAppleNotesSync?.() }]
            : []),
        ]
      : []),
    ...(state.serverUrl ? [{ label: `服务器：${state.serverUrl}`, enabled: false }] : []),
    ...(isPlaintextFallback()
      ? [{ label: '⚠ 未检测到系统密钥环，凭据以明文保存在本地', enabled: false }]
      : []),
    { type: 'separator' },
    {
      label: '退出 aiMarkdown',
      click: () => {
        setQuitting(true);
        if (onQuit) onQuit();
        else app.quit();
      },
    },
  ]);

  tray.setContextMenu(menu);
  tray.setToolTip(`aiMarkdown — ${syncLabel}`);
}

export function createTray(): Tray {
  if (tray && !tray.isDestroyed()) {
    rebuildMenu();
    return tray;
  }
  tray = new Tray(trayImage());
  tray.on('click', () => {
    // On macOS a click opens the menu automatically; on Windows/Linux make it summon capture.
    if (process.platform !== 'darwin') toggleCaptureWindow();
  });
  rebuildMenu();
  return tray;
}

export function destroyTray(): void {
  if (tray && !tray.isDestroyed()) tray.destroy();
  tray = null;
}

export { getCaptureWindow, createMainWindow };
